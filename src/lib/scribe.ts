import type { FormField } from "@/lib/forms";

type ScribeInput = {
  instructions: string;
  sections: FormField[];
  transcript: string;
  clientFirstName: string;
  coachName: string;
};

const STOP = new Set(
  "the a an and or of to in on for with about be is are was were that this it as at by from their his her your you i we they them what how why include including discussion around other any any".split(
    " ",
  ),
);

function keywords(text: string) {
  return text
    .toLowerCase()
    .replace(/[^a-z\s]/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 3 && !STOP.has(w));
}

function sentences(transcript: string) {
  return transcript
    .split(/\n+/)
    .flatMap((line) => {
      const match = line.match(/^\s*([A-Za-z][\w .'-]{0,30}):\s*(.+)$/);
      const speaker = match ? match[1].trim() : "";
      const body = match ? match[2] : line;
      return body
        .split(/(?<=[.!?])\s+/)
        .map((text) => ({ speaker, text: text.trim() }))
        .filter((s) => s.text.length > 0);
    });
}

function isCoachSpeaker(speaker: string, coachName: string) {
  const s = speaker.toLowerCase();
  return s === "coach" || (coachName && coachName.toLowerCase().split(" ").some((part) => part && s.includes(part)));
}

/** Section labels that match a trigger also look for these cue words in the transcript. */
const CONCEPTS: Array<[RegExp, string[]]> = [
  [/who|about|context|interest|background/i, ["love", "like", "enjoy", "freshman", "sophomore", "junior", "senior", "grade", "family", "play", "interested"]],
  [/want|hope|goal|reached/i, ["want", "hope", "goal", "wish", "need", "trying", "plan"]],
  [/strength/i, ["good", "organized", "proud", "strength", "able", "skill", "best"]],
  [/next|action|plan|step/i, ["will", "next", "draft", "list", "before", "going", "talk", "review", "homework"]],
  [/progress|win|growth/i, ["finished", "did", "done", "improved", "better", "won", "managed", "started"]],
  [/challenge|still open/i, ["hard", "stress", "stressed", "worried", "struggle", "difficult", "anxious", "behind"]],
];

/** Local fallback: answers each section with the most relevant lines of the transcript. */
export function heuristicScribe(input: ScribeInput) {
  const all = sentences(input.transcript).filter((s) => !s.text.trim().endsWith("?"));
  const sections = input.sections.length
    ? input.sections
    : [{ id: "summary", label: "Session summary", type: "longtext" as const }];
  const used = new Set<number>();

  const output = sections.map((section) => {
    const wantsQuotes = /quote/i.test(section.label);
    const terms = [
      ...keywords(section.label),
      ...CONCEPTS.filter(([trigger]) => trigger.test(section.label)).flatMap(([, cues]) => cues),
    ];
    const scored = all
      .map((s, index) => ({
        ...s,
        index,
        score:
          keywords(s.text).filter((w) => terms.some((t) => w.startsWith(t.slice(0, 5)))).length +
          (s.speaker && !isCoachSpeaker(s.speaker, input.coachName) ? 0.5 : 0) -
          (used.has(index) ? 1 : 0),
      }))
      .filter((s) => s.score >= 1 || terms.length === 0);

    if (wantsQuotes) {
      const quotes = all
        .filter((s) => s.speaker && !isCoachSpeaker(s.speaker, input.coachName) && s.text.length > 25)
        .slice(0, 3)
        .map((s) => `"${s.text}"`);
      return `${section.label}\n${quotes.length ? quotes.map((q) => `• ${q}`).join("\n") : "• No direct quotes captured."}`;
    }

    const picked = scored
      .sort((a, b) => b.score - a.score)
      .slice(0, 3)
      .sort((a, b) => a.index - b.index)
      .map((s) => {
        used.add(s.index);
        const who = s.speaker
          ? isCoachSpeaker(s.speaker, input.coachName)
            ? "The coach"
            : input.clientFirstName
          : "";
        return who ? `${who} noted: ${s.text}` : s.text;
      });

    return `${section.label}\n${picked.length ? picked.map((p) => `• ${p}`).join("\n") : "• Not discussed in this session."}`;
  });

  return [
    ...output,
    "",
    "Draft generated by the local scribe. Review and edit before saving. Parents never receive these notes.",
  ].join("\n\n");
}

export async function generateScribeNotes(input: ScribeInput): Promise<{ notes: string; engine: string }> {
  const key = process.env.ANTHROPIC_API_KEY;
  if (!key) return { notes: heuristicScribe(input), engine: "local" };

  const sectionList = input.sections.length
    ? input.sections.map((s, i) => `${i + 1}. ${s.label}`).join("\n")
    : "1. Session summary";

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": key,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify({
        model: process.env.ANTHROPIC_MODEL || "claude-sonnet-4-5",
        max_tokens: 2000,
        system:
          "You are a careful scribe for a teen coaching program. Write factual chart notes only from the transcript. Never invent details. If a section was not discussed, say so. Keep the student's confidentiality in mind.",
        messages: [
          {
            role: "user",
            content: `Manager instructions:\n${input.instructions || "Summarize the session for coach follow-up."}\n\nStudent: ${input.clientFirstName}\nCoach: ${input.coachName}\n\nFill in each section, with a heading per section:\n${sectionList}\n\nTranscript:\n${input.transcript}`,
          },
        ],
      }),
    });
    if (!response.ok) throw new Error(`Claude returned ${response.status}`);
    const data = (await response.json()) as { content?: Array<{ type: string; text?: string }> };
    const text = data.content?.find((c) => c.type === "text")?.text?.trim();
    if (!text) throw new Error("Empty response");
    return { notes: text, engine: "claude" };
  } catch {
    return { notes: heuristicScribe(input), engine: "local (Claude unavailable)" };
  }
}
